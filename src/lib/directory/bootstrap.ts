import "server-only";
import { promises as fs } from "fs";
import path from "path";
import { dataDir, readJson, writeJson } from "../store";
import { generateBootstrapToken, generateMachineKey, normalizeCode } from "./codes";
import { can, ROOT_SCOPE } from "./can";
import type { Directory, Principal } from "./types";

const TOKEN_FILE = "bootstrap.json";
const TOKEN_TTL_MS = 24 * 60 * 60 * 1000;

interface BootstrapFile {
  token: string;
  expiresAt: string;
  claimedAt?: string;
}

let claimQueue: Promise<unknown> = Promise.resolve();

/** True when somebody can change access. Until then, the install is unclaimed. */
export function hasOwner(directory: Directory): boolean {
  return directory.principals.some(
    (principal) =>
      !principal.disabledAt &&
      can(directory, principal.id, "directory.write", ROOT_SCOPE).allowed
  );
}

/**
 * The token is stored in clear in a 0600 file, not only as a hash, so that a
 * restart can print the same unclaimed token instead of invalidating the one
 * the operator is halfway through typing. The file is the secret; hashing it
 * would not add a boundary the data directory does not already cross.
 */
export async function ensureBootstrapToken(): Promise<string | null> {
  const existing = await readJson<BootstrapFile | null>(TOKEN_FILE, null);
  const now = Date.now();
  if (existing && !existing.claimedAt && Date.parse(existing.expiresAt) > now) {
    return existing.token;
  }
  const token = generateBootstrapToken();
  const target = path.join(dataDir(), TOKEN_FILE);
  await writeJson(TOKEN_FILE, {
    token,
    expiresAt: new Date(now + TOKEN_TTL_MS).toISOString(),
  } satisfies BootstrapFile);
  await fs.chmod(target, 0o600).catch(() => undefined);
  return token;
}

export function claimBootstrapToken(input: string): Promise<boolean> {
  const run = claimQueue.then(async () => {
    const file = await readJson<BootstrapFile | null>(TOKEN_FILE, null);
    if (!file || file.claimedAt) return false;
    if (Date.parse(file.expiresAt) <= Date.now()) return false;
    if (normalizeCode(input) !== normalizeCode(file.token)) return false;
    await writeJson(TOKEN_FILE, { ...file, claimedAt: new Date().toISOString() });
    return true;
  });
  claimQueue = run.then(
    () => undefined,
    () => undefined
  );
  return run;
}

export function machineKeyPath(): string {
  return path.join(dataDir(), "machine.key");
}

/**
 * The key that lets the desktop shell sign in without a prompt. Generated by
 * the server on first start, read by the shell from the same data directory.
 * Anyone who can read this file can already read the whole directory.
 */
export async function ensureMachineKey(): Promise<string> {
  const target = machineKeyPath();
  try {
    const existing = (await fs.readFile(target, "utf8")).trim();
    if (existing) return existing;
  } catch {
    // No key yet.
  }
  const key = generateMachineKey();
  await fs.mkdir(dataDir(), { recursive: true });
  await fs.writeFile(target, key, { mode: 0o600 });
  await fs.chmod(target, 0o600).catch(() => undefined);
  return key;
}

/**
 * The desktop shell writes this file with mode 0600. Reading it proves the
 * caller can already act as the OS user who owns the data directory, which is
 * the only proof of deployment control a local install has.
 */
export async function readMachineKey(): Promise<string | null> {
  try {
    const target = machineKeyPath();
    const stat = await fs.stat(target);
    if (process.platform !== "win32" && (stat.mode & 0o077) !== 0) {
      console.warn(
        `openFoundry: ignoring ${target} because it is readable by other users (mode ${(stat.mode & 0o777).toString(8)}).`
      );
      return null;
    }
    const value = (await fs.readFile(target, "utf8")).trim();
    return value || null;
  } catch {
    return null;
  }
}

/** The person this computer should sign in as, when no prompt is possible. */
export function localPrincipal(
  directory: Directory,
  email: string
): Principal | undefined {
  const wanted = email.trim().toLowerCase();
  const match = directory.principals.find(
    (principal) =>
      !principal.disabledAt &&
      principal.email.toLowerCase() === wanted &&
      can(directory, principal.id, "directory.write", ROOT_SCOPE).allowed
  );
  if (match) return match;
  return directory.principals.find(
    (principal) =>
      !principal.disabledAt &&
      can(directory, principal.id, "directory.write", ROOT_SCOPE).allowed
  );
}
